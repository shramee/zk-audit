// Package report renders the inventory as Markdown: inventory.md and the
// draft binding-table.md.
package report

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/shramee/zk-audit/plugins/zk-audit/skills/zk-audit/tools/gnark-inventory/internal/inventory"
	"github.com/shramee/zk-audit/plugins/zk-audit/skills/zk-audit/tools/gnark-inventory/internal/solidity"
)

func esc(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(esc(s), "`", "'") + "`"
}

func loc(p inventory.Pos) string {
	if p.File == "" {
		return "?"
	}
	if p.Line == 0 {
		return p.File
	}
	return fmt.Sprintf("%s:%d", p.File, p.Line)
}

func count(n int) string {
	if n < 0 {
		return "dynamic"
	}
	return strconv.Itoa(n)
}

// Inventory renders inventory.md.
func Inventory(inv *inventory.Inventory) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# gnark inventory\n\n")
	w("Generated by gnark-inventory %s. Load mode: **%s**", inv.ToolVersion, inv.LoadMode)
	if inv.LoadMode != "types" {
		w(" (results marked unresolved need type information; see load errors)")
	}
	w(".\n\n")
	if len(inv.Scope) > 0 {
		w("Scope: %s\n\n", strings.Join(inv.Scope, ", "))
	}
	s := inv.Summary
	w("| Go files | gnark files | circuits | static public inputs | hint sites | unreached hint outputs | Solidity files | verify calls |\n|---|---|---|---|---|---|---|---|\n")
	w("| %d | %d | %d | %d | %d | %d | %d | %d |\n\n", s.GoFiles, s.GnarkFiles, s.Circuits, s.PublicInputs, s.HintSites, s.UnreachedHints, s.SolidityFiles, s.VerifyCalls)

	w("## Circuits\n\n")
	if len(inv.Circuits) == 0 {
		w("No type with `Define(frontend.API) error` was found.\n\n")
	} else {
		w("| Circuit | Defined at | Public | Secret | Layout | Hints | Footguns |\n|---|---|---|---|---|---|---|\n")
		for _, c := range inv.Circuits {
			tag := ""
			if c.InTest {
				tag = " (test)"
			}
			res := c.Witness.Source
			if !c.Witness.Resolved {
				res += ", unresolved"
			}
			w("| %s%s | %s | %s | %s | %s | %d | %d |\n", code(c.Name), tag, loc(c.Define), count(c.Witness.NbPublic), count(c.Witness.NbSecret), res, len(c.HintIDs), len(c.FootgunIDs))
		}
		w("\n")
		for _, c := range inv.Circuits {
			writeCircuit(&b, c)
		}
	}

	w("## Hint call sites\n\n")
	if len(inv.Hints) == 0 {
		w("None found.\n\n")
	} else {
		w("Reachability is a heuristic taint pass inside the calling function: `reached` means an output flows into at least one constraining call (Assert*, ToBinary, range check, recomposition). It does **not** prove the output is fully bound. `unreached` outputs are pre-flagged.\n\n")
		w("| Id | Site | Function | Hint | Outputs | Status | Unreached / escaping outputs |\n|---|---|---|---|---|---|---|\n")
		for _, h := range inv.Hints {
			var bad []string
			for _, o := range h.Outputs {
				switch o.Status {
				case "unreached":
					bad = append(bad, "["+o.Index+"] unreached")
				case "escapes":
					bad = append(bad, "["+o.Index+"] escapes via "+strings.Join(o.Escapes, ", "))
				}
			}
			t := ""
			if h.InTest {
				t = " (test)"
			}
			w("| %s%s | %s | %s | %s | %s | **%s** | %s |\n", h.ID, t, loc(h.Pos), code(h.Function), code(h.HintFunc), esc(h.NbOutputs), h.Status, esc(strings.Join(bad, "; ")))
		}
		w("\n")
	}
	if len(inv.HintFuncs) > 0 {
		w("### Hint functions\n\n| Function | Declared at | Registered | Call sites |\n|---|---|---|---|\n")
		for _, h := range inv.HintFuncs {
			w("| %s | %s | %v | %d |\n", code(h.Name), loc(h.Pos), h.Registered, h.CallSites)
		}
		w("\n")
	}

	w("## Footgun hits\n\n")
	writeFootguns(&b, inv)

	w("## Contracts\n\n")
	writeContracts(&b, inv.Contracts)

	if len(inv.LoadErrors) > 0 {
		w("## Load errors\n\n")
		for i, e := range inv.LoadErrors {
			if i == 20 {
				w("- ... %d more in inventory.json\n", len(inv.LoadErrors)-20)
				break
			}
			w("- %s\n", esc(e))
		}
		w("\n")
	}
	return b.String()
}

func writeCircuit(b *strings.Builder, c *inventory.Circuit) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	w("### %s\n\n", c.Name)
	w("Package `%s`, type at %s, `Define` at %s.\n\n", c.Package, loc(c.Decl), loc(c.Define))
	w("**Public witness, in order** (this is the order the verifier contract must pass):\n\n")
	writeGroups(b, c.Witness.Public)
	w("**Secret witness:**\n\n")
	writeGroups(b, c.Witness.Secret)
	if len(c.Witness.Omit) > 0 {
		w("Fields tagged `gnark:\"-\"` (not in the witness): ")
		var xs []string
		for _, o := range c.Witness.Omit {
			xs = append(xs, code(o.GoPath)+" at "+loc(o.Decl))
		}
		w("%s.\n\n", strings.Join(xs, ", "))
	}
	if len(c.Witness.Notes) > 0 {
		w("Notes:\n\n")
		for _, n := range c.Witness.Notes {
			w("- %s\n", esc(n))
		}
		w("\n")
	}
}

func writeGroups(b *strings.Builder, gs []*inventory.Group) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	if len(gs) == 0 {
		w("_none_\n\n")
		return
	}
	w("| Index | gnark name | Go path | Type | Leaves | Declared | Note |\n|---|---|---|---|---|---|---|\n")
	for _, g := range gs {
		idx := g.StartExpr
		if g.Len > 1 && g.Start >= 0 {
			idx = fmt.Sprintf("%d–%d", g.Start, g.Start+g.Len-1)
		}
		w("| %s | %s | %s | %s | %s | %s | %s |\n", esc(idx), code(g.Name), code(g.GoPath), code(g.Type), count(g.Len), loc(g.Decl), esc(g.Note))
	}
	w("\n")
}

func writeFootguns(b *strings.Builder, inv *inventory.Inventory) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	byID := map[string][]*inventory.Footgun{}
	for _, f := range inv.Footguns {
		byID[f.ID] = append(byID[f.ID], f)
	}
	any := false
	for _, r := range inventory.Rules {
		hits := byID[r.ID]
		if len(hits) == 0 {
			continue
		}
		any = true
		var prod, test []*inventory.Footgun
		for _, h := range hits {
			if h.InTest {
				test = append(test, h)
			} else {
				prod = append(prod, h)
			}
		}
		w("### %s — %s (%d", r.ID, r.Title, len(prod))
		if len(test) > 0 {
			w(", plus %d in tests", len(test))
		}
		w(")\n\n%s\n\n", r.Note)
		for _, h := range prod {
			extra := ""
			if h.Circuit != "" {
				extra = " · circuit " + code(h.Circuit)
			} else if h.Function != "" {
				extra = " · " + code(h.Function)
			}
			w("- %s %s%s — %s\n", h.Key, loc(h.Pos), extra, code(h.Snippet))
			if n := strings.TrimSpace(strings.TrimSuffix(h.Note, r.Note)); n != "" && n != h.Note {
				w("  - %s\n", esc(n))
			}
		}
		if len(prod) > 0 {
			w("\n")
		}
	}
	if !any {
		w("None.\n\n")
	}
}

func writeContracts(b *strings.Builder, c *solidity.Result) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	if c == nil || len(c.Files) == 0 {
		w("No Solidity sources in scope.\n\n")
		return
	}
	w("%d Solidity files scanned (Foundry `lib/`, `*.t.sol` and `*.s.sol` skipped). The scan is lexical; check each line.\n\n", len(c.Files))
	if len(c.Verifiers) > 0 {
		w("### Verifier contracts\n\n| Contract | File | Kind | Public inputs | Commitments |\n|---|---|---|---|---|\n")
		for _, v := range c.Verifiers {
			w("| %s | %s:%d | %s | %s | %v |\n", code(v.Contract), v.File, v.Line, v.Kind, count(v.NbPublic), v.Commitments)
		}
		w("\n")
	}
	if len(c.VerifyCalls) > 0 {
		w("### Verification call sites\n\n| Site | Contract.function | Call | Input argument | Result used |\n|---|---|---|---|---|\n")
		for _, v := range c.VerifyCalls {
			call := v.Callee
			if v.Receiver != "" {
				call = v.Receiver + "." + call
			}
			w("| %s:%d | %s | %s | %s | %v |\n", v.File, v.Line, code(v.Contract+"."+v.Function), code(call), code(v.InputArg), v.ResultUsed)
		}
		w("\n")
	}
	if len(c.StateVars) > 0 {
		w("### Proof-related state\n\n| Variable | Kind | Declared | Accesses |\n|---|---|---|---|\n")
		for _, s := range c.StateVars {
			var acc []string
			for _, a := range c.StateAccess {
				if a.Contract == s.Contract && a.Name == s.Name {
					acc = append(acc, fmt.Sprintf("%s %s:%d (%s)", a.Op, a.File, a.Line, a.Function))
				}
			}
			w("| %s | %s | %s:%d | %s |\n", code(s.Contract+"."+s.Name), s.Kind, s.File, s.Line, esc(strings.Join(acc, "; ")))
		}
		w("\n")
	}
}

// BindingTable renders the draft binding-table.md.
func BindingTable(inv *inventory.Inventory) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Public-input binding table (draft)\n\n")
	w("One row per public input, in public-witness order. The tool fills what it can see; `?` cells must be completed by the reviewer and stay `?` until checked. Columns: circuit field · index · contract source expression · range-checked? · bound to sender / chain / contract / nonce?\n\n")
	var circuits []*inventory.Circuit
	for _, c := range inv.Circuits {
		if !c.InTest {
			circuits = append(circuits, c)
		}
	}
	calls := []solidity.VerifyCall{}
	if inv.Contracts != nil {
		calls = inv.Contracts.VerifyCalls
	}
	matched := map[string]bool{}
	for _, vc := range calls {
		assigns := inputsFor(inv.Contracts, vc)
		n := len(assigns)
		var cands []*inventory.Circuit
		for _, c := range circuits {
			if c.Witness.NbPublic == n && n > 0 {
				cands = append(cands, c)
			}
		}
		w("## %s.%s → %s (%s:%d)\n\n", vc.Contract, vc.Function, vc.Callee, vc.File, vc.Line)
		switch {
		case n == 0:
			w("The input array %s was not built element by element in this function; map it by hand.\n\n", code(vc.InputArg))
		case len(cands) == 0:
			w("No circuit has %d static public inputs; map it by hand.\n\n", n)
		case len(cands) > 1:
			var names []string
			for _, c := range cands {
				names = append(names, c.Name)
			}
			w("Several circuits have %d public inputs (%s); the first is shown, confirm which one this verifier was built from.\n\n", n, strings.Join(names, ", "))
		}
		var leaves []leaf
		if len(cands) > 0 {
			leaves = expand(cands[0].Witness.Public)
			matched[cands[0].Name] = true
			w("Circuit: %s (%s).\n\n", code(cands[0].Name), loc(cands[0].Define))
		}
		rows := n
		if len(leaves) > rows {
			rows = len(leaves)
		}
		w("| # | Circuit field | Contract source expr | Range-checked? | Bound to sender/chain/contract/nonce? | Notes |\n|---|---|---|---|---|---|\n")
		for i := 0; i < rows; i++ {
			field, expr, note := "?", "?", ""
			if i < len(leaves) {
				field = code(leaves[i].name) + " (" + code(leaves[i].goPath) + ")"
			} else if len(leaves) > 0 {
				note = "extra contract input with no circuit field"
			}
			if a, ok := assigns[i]; ok {
				expr = code(a.Expr) + fmt.Sprintf(" (L%d)", a.Line)
				if strings.Contains(a.Expr, "keccak") || strings.Contains(a.Expr, "sha256") {
					note = joinNote(note, "hash output: check reduction mod r / truncation")
				}
			} else if n > 0 {
				note = joinNote(note, "no contract assignment for this index")
			}
			bound := "?"
			if a, ok := assigns[i]; ok {
				if m := solidity.MentionsBinding(a.Expr); len(m) > 0 {
					bound = strings.Join(m, ", ")
				}
			}
			w("| %d | %s | %s | ? | %s | %s |\n", i, field, expr, bound, esc(note))
		}
		w("\n")
	}
	for _, c := range circuits {
		if matched[c.Name] {
			continue
		}
		w("## %s (no matching verification call found)\n\n", c.Name)
		w("| # | Circuit field | Contract source expr | Range-checked? | Bound to sender/chain/contract/nonce? | Notes |\n|---|---|---|---|---|---|\n")
		for i, l := range expand(c.Witness.Public) {
			w("| %s | %s (%s) | ? | ? | ? | %s |\n", l.index, code(l.name), code(l.goPath), esc(l.note))
			_ = i
		}
		if len(c.Witness.Public) == 0 {
			w("| – | _no public inputs_ | | | | a proof with no public inputs binds nothing on-chain |\n")
		}
		w("\n")
	}
	if len(circuits) == 0 && len(calls) == 0 {
		w("No circuits and no verification calls in scope.\n")
	}
	return b.String()
}

func joinNote(a, b string) string {
	if a == "" {
		return b
	}
	return a + "; " + b
}

type leaf struct {
	index, name, goPath, note string
}

// expand turns groups into one row per leaf where the length is static.
func expand(gs []*inventory.Group) []leaf {
	var out []leaf
	for _, g := range gs {
		switch {
		case g.Len == 1:
			out = append(out, leaf{index: g.StartExpr, name: g.Name, goPath: g.GoPath})
		case g.Len > 1 && g.Len <= 64 && g.Start >= 0 && !strings.Contains(g.Name, "{i}"):
			for i := 0; i < g.Len; i++ {
				out = append(out, leaf{index: strconv.Itoa(g.Start + i), name: g.Name + "_" + strconv.Itoa(i), goPath: fmt.Sprintf("%s[%d]", g.GoPath, i)})
			}
		default:
			out = append(out, leaf{index: g.StartExpr, name: g.Name, goPath: g.GoPath, note: "group of " + count(g.Len) + " leaves: " + g.Note})
		}
	}
	return out
}

func inputsFor(c *solidity.Result, vc solidity.VerifyCall) map[int]solidity.InputAssign {
	out := map[int]solidity.InputAssign{}
	if c == nil {
		return out
	}
	arr := strings.TrimSpace(vc.InputArg)
	inline := strings.HasPrefix(arr, "[")
	for _, a := range c.InputAssigns {
		if a.File != vc.File || a.Contract != vc.Contract || a.Function != vc.Function {
			continue
		}
		if (inline && a.Array == "(inline)" && a.Line == vc.Line) || (!inline && a.Array == arr) {
			out[a.Index] = a
		}
	}
	return out
}

// SortedIDs is a helper for deterministic output in callers.
func SortedIDs(m map[string]int) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}
